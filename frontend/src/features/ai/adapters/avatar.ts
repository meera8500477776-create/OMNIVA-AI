/** Browser-facing avatar lifecycle and lip-sync events; speech comes from an independent TTS provider. */
export type AvatarMode = "demo" | "live";
export type AvatarEventType = "session_started" | "tts_started" | "lip_sync_started" | "interrupted" | "error" | "session_ended";

export interface AvatarEvent {
  type: AvatarEventType;
  sessionId: string;
  mode: AvatarMode;
  simulation: boolean;
  message?: string;
  sequence: number;
  createdAt: string;
}

export interface TtsOutput {
  /** Implemented by an independently selected TTS provider. This adapter does not synthesize speech. */
  synthesize(text: string, signal: AbortSignal): Promise<MediaStream>;
  providerName: string;
}

export interface AvatarRenderer {
  attachAudioStream(stream: MediaStream): void | Promise<void>;
  stop(): void | Promise<void>;
}

export class AvatarAdapterError extends Error {
  readonly code: string;
  constructor(code: string, message: string) {
    super(message);
    this.code = code;
    this.name = "AvatarAdapterError";
  }
}

export class AvatarSession {
  readonly sessionId: string;
  readonly mode: AvatarMode;
  readonly events: AvatarEvent[] = [];
  private sequence = 0;
  private active = false;
  private aborter?: AbortController;
  private stream?: MediaStream;
  private readonly renderer: AvatarRenderer;
  private readonly tts?: TtsOutput;
  private readonly timeoutMs: number;

  constructor(
    sessionId: string,
    mode: AvatarMode,
    renderer: AvatarRenderer,
    tts?: TtsOutput,
    timeoutMs = 8000,
  ) {
    if (!sessionId.trim()) throw new AvatarAdapterError("invalid_session", "sessionId is required");
    if (!Number.isFinite(timeoutMs) || timeoutMs < 50 || timeoutMs > 120000) {
      throw new AvatarAdapterError("invalid_timeout", "timeoutMs must be between 50 and 120000");
    }
    this.sessionId = sessionId;
    this.mode = mode;
    this.renderer = renderer;
    this.tts = tts;
    this.timeoutMs = timeoutMs;
  }

  start(): AvatarEvent {
    if (this.active) throw new AvatarAdapterError("session_state_conflict", "Avatar session is already active");
    this.active = true;
    return this.emit("session_started", this.mode === "demo", "Avatar session is ready");
  }

  /** Demo intentionally produces no speech or lip-sync. Live TTS is injected; no provider is bundled here. */
  async speak(text: string): Promise<AvatarEvent> {
    this.ensureActive();
    if (!text.trim() || text.length > 2000) throw new AvatarAdapterError("invalid_text", "Text must contain 1 to 2000 characters");
    if (this.mode === "demo") {
      return this.emit("tts_started", true, "Simulated speech request; no audio was generated");
    }
    if (!this.tts) throw new AvatarAdapterError("provider_unavailable", "Independent TTS provider is not configured");
    this.aborter = new AbortController();
    let timeout: ReturnType<typeof setTimeout> | undefined;
    try {
      const deadline = new Promise<never>((_, reject) => {
        timeout = setTimeout(() => {
          this.aborter?.abort();
          reject(new AvatarAdapterError("provider_timeout", "TTS provider timed out"));
        }, this.timeoutMs);
      });
      const stream = await Promise.race([this.tts.synthesize(text, this.aborter.signal), deadline]);
      if (this.aborter.signal.aborted || !this.active) {
        for (const track of stream.getTracks()) track.stop();
        throw new AvatarAdapterError("cancelled", "Speech request was cancelled");
      }
      this.stream = stream;
      this.emit("tts_started", false, "Speech generated by the independent provider");
      await this.renderer.attachAudioStream(stream);
      return this.emit("lip_sync_started", false, "Lip-sync is driven by the supplied TTS audio stream");
    } catch (error) {
      const safeMessage = error instanceof AvatarAdapterError ? error.message : "Avatar speech provider failed";
      if (this.aborter?.signal.aborted && !(error instanceof AvatarAdapterError && error.code === "provider_timeout")) {
        this.emit("interrupted", false, "Avatar speech request was cancelled");
        throw new AvatarAdapterError("cancelled", "Speech request was cancelled");
      }
      this.emit("error", false, safeMessage);
      if (error instanceof AvatarAdapterError) throw error;
      throw new AvatarAdapterError("provider_error", "TTS or renderer failed");
    } finally {
      if (timeout) clearTimeout(timeout);
      this.aborter = undefined;
    }
  }

  async attachAudioStream(stream: MediaStream): Promise<AvatarEvent> {
    this.ensureActive();
    if (this.mode === "demo") throw new AvatarAdapterError("demo_audio_disabled", "Demo mode does not attach real audio");
    this.stream = stream;
    await this.renderer.attachAudioStream(stream);
    return this.emit("lip_sync_started", false, "Lip-sync is driven by an external audio stream");
  }

  async cancel(): Promise<AvatarEvent> {
    this.aborter?.abort();
    await this.stopStream();
    await this.renderer.stop();
    return this.emit("interrupted", this.mode === "demo", "Avatar audio/rendering was stopped");
  }

  async end(): Promise<AvatarEvent> {
    this.aborter?.abort();
    this.active = false;
    await this.stopStream();
    await this.renderer.stop();
    return this.emit("session_ended", this.mode === "demo", "Avatar session ended");
  }

  private ensureActive(): void {
    if (!this.active) throw new AvatarAdapterError("session_state_conflict", "Avatar session is not active");
  }

  private async stopStream(): Promise<void> {
    if (this.stream) {
      for (const track of this.stream.getTracks()) track.stop();
      this.stream = undefined;
    }
  }

  private emit(type: AvatarEventType, simulation: boolean, message: string): AvatarEvent {
    const event: AvatarEvent = {
      type, sessionId: this.sessionId, mode: this.mode, simulation,
      message, sequence: ++this.sequence, createdAt: new Date().toISOString(),
    };
    this.events.push(event);
    return event;
  }
}
